source("evaluation_helpers.R")
training <- data.frame(Age = c(20, 30, 40, 50), Duration = c(4, 8, 12, 16))
test <- data.frame(Age = 1000, Duration = 400)
scaler <- fit_credit_preprocessor(training, names(training))
stopifnot(isTRUE(all.equal(unname(scaler$mean), c(35, 10))))
before <- scaler$mean
predict(scaler, test)
stopifnot(identical(before, scaler$mean))
truth <- factor(c("Bad", "Bad", "Good", "Good"), levels = c("Bad", "Good"))
data <- data.frame(obs = truth, pred = truth, Good = c(0.1, 0.2, 0.8, 0.9))
metrics <- credit_summary(data)
stopifnot(metrics["F"] == 1, metrics["ROC"] == 1)
threshold <- choose_credit_threshold(c(0.1, 0.2, 0.4, 0.5), truth)
stopifnot(threshold > 0.2, threshold <= 0.4)
cat("Train-only scaling and metric/threshold regression checks passed.\n")
